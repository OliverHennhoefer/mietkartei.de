import { getTableColumns, getTableName } from 'drizzle-orm';
import { getTableConfig, type SQLiteColumn, type SQLiteTable } from 'drizzle-orm/sqlite-core';
import { readFileSync, writeFileSync } from 'node:fs';
import { format } from 'prettier';
import ts from 'typescript';
import { describe, expect, it } from 'vitest';
import { accounts, leases, leaseTenants } from './db/schema';
import { EXPORT_FORMAT, EXPORT_VERSION, exportTables } from './export';
import { readableTables } from './export-csv';

// .github/EXPORT_FORMAT.md describes export.json table by table, from the schema and its doc
// comments, so the reference cannot drift from what an export holds. After a schema change run
// `UPDATE_EXPORT_FORMAT=1 npx vitest run src/lib/server/export-format.spec.ts` in app/.

const SCHEMA = 'src/lib/server/db/schema.ts';
const REFERENCE = '../.github/EXPORT_FORMAT.md';

type Comments = { table?: string; fields: Map<string, string> };

/** The doc comment of every table and of every column property, from the schema source. */
function schemaComments(): Map<string, Comments> {
	const source = ts.createSourceFile(
		SCHEMA,
		readFileSync(SCHEMA, 'utf8'),
		ts.ScriptTarget.Latest,
		true
	);
	const text = (node: ts.Node) =>
		ts
			.getJSDocCommentsAndTags(node)
			.filter(ts.isJSDoc)
			.map((doc) => ts.getTextOfJSDocComment(doc.comment) ?? '')
			.join(' ')
			.replace(/\s+/g, ' ')
			.trim();
	const comments = new Map<string, Comments>();
	for (const statement of source.statements) {
		if (!ts.isVariableStatement(statement)) continue;
		for (const declaration of statement.declarationList.declarations) {
			const call = declaration.initializer;
			if (!call || !ts.isCallExpression(call) || call.expression.getText() !== 'sqliteTable') {
				continue;
			}
			const [name, columns] = call.arguments;
			if (!ts.isStringLiteral(name) || !ts.isObjectLiteralExpression(columns)) continue;
			const fields = new Map<string, string>();
			for (const property of columns.properties) {
				if (ts.isPropertyAssignment(property)) fields.set(property.name.getText(), text(property));
			}
			comments.set(name.text, { table: text(statement) || undefined, fields });
		}
	}
	return comments;
}

function typeOf(column: SQLiteColumn): string {
	const values = (column as { enumValues?: string[] }).enumValues;
	if (values && values.length > 0) return values.map((value) => `\`${value}\``).join(', ');
	switch (column.columnType) {
		case 'SQLiteTimestamp':
			return 'timestamp (ISO 8601)';
		case 'SQLiteBoolean':
			return 'boolean';
		case 'SQLiteInteger':
			return 'integer';
		case 'SQLiteReal':
			return 'number';
		default:
			return 'text';
	}
}

function referencesOf(table: SQLiteTable): Map<string, string> {
	const references = new Map<string, string>();
	for (const foreignKey of getTableConfig(table).foreignKeys) {
		const reference = foreignKey.reference();
		reference.columns.forEach((column, index) => {
			const target = reference.foreignColumns[index];
			references.set(column.name, `${getTableName(reference.foreignTable)}.${target.name}`);
		});
	}
	return references;
}

const cell = (value: string) => value.replaceAll('|', '\\|');

/** The reference as it should be. */
function reference(): string {
	const comments = schemaComments();
	const tables = [
		accounts,
		...exportTables.flatMap((table) => (table === leases ? [table, leaseTenants] : [table]))
	];
	const lines = [
		'# Export format',
		'',
		'<!-- Generated by app/src/lib/server/export-format.spec.ts from the schema. Do not edit by hand. -->',
		'',
		'**Einstellungen → Export** downloads a ZIP with every record of an account. This page describes its files so that another program can read them without mietkartei. The user guide is [Umziehen und Daten mitnehmen](https://docs.mietkartei.de/anleitungen/umziehen/).',
		'',
		'## Files',
		'',
		'- `export.json`: every table of the account, described below.',
		'- `documents/<id>-<name>`: every uploaded document as uploaded; `<id>` is its row in `documents`.',
		'- `FEHLENDE-DOKUMENTE.txt`: only when a document row has no file in storage; lists those documents.',
		`- \`tabellen/*.csv\`: ${readableTables.map((table) => `\`${table.file}\``).join(', ')}. The main records once more as spreadsheets, with the same columns as the CSV import (**Einstellungen → Datenübernahme**): semicolons, UTF-8 with byte order mark, amounts like \`650,00\`, dates like \`01.01.2025\`. They are a convenience copy; \`export.json\` is complete.`,
		'',
		'## export.json',
		'',
		'```json',
		`{ "format": "${EXPORT_FORMAT}", "version": ${EXPORT_VERSION}, "schema": "<last migration>", "exportedAt": "<ISO 8601>", "accountId": "<id>", "tables": { "<table>": [ { "<field>": <value> } ] } }`,
		'```',
		'',
		`- \`format\` is always \`${EXPORT_FORMAT}\`, \`version\` ${EXPORT_VERSION} for this layout of the file.`,
		'- `schema` is the last database migration of the instance that wrote the file (see `app/drizzle/`). A newer instance upgrades the rows of an older export when it restores it ([MIGRATIONS.md](MIGRATIONS.md#exports-from-older-versions)); exports written before November 27, 2026 have no `schema`.',
		'- `tables` holds one array of rows per table, parents before children, so the rows can be created in order. A row is an object keyed by the field names below (not the SQL column names).',
		'- Amounts are integer euro cents (`65000` = 650,00 €) unless a field says otherwise. Dates are ISO strings (`2025-01-31`), months `2025-01`. Timestamps are ISO 8601 strings in UTC. Ids are UUIDs, except where a field says otherwise.',
		'- `users` leaves out password hashes. API keys, bank connection sessions and notification channels are not exported: they are credentials of the instance, not the landlord’s data.',
		'',
		'## Tables',
		''
	];
	for (const table of tables) {
		const name = getTableName(table);
		const comment = comments.get(name);
		const references = referencesOf(table);
		lines.push(`### \`${name}\``, '');
		if (comment?.table) lines.push(comment.table, '');
		lines.push('| Field | Type | Required | Description |', '| --- | --- | --- | --- |');
		for (const [key, column] of Object.entries(getTableColumns(table))) {
			const required = column.notNull && !column.hasDefault ? 'yes' : '';
			const target = references.get(column.name);
			const description = [comment?.fields.get(key), target && `References \`${target}\`.`]
				.filter(Boolean)
				.join(' ');
			lines.push(`| \`${key}\` | ${cell(typeOf(column))} | ${required} | ${cell(description)} |`);
		}
		lines.push('');
	}
	return lines.join('\n');
}

describe('export format reference', () => {
	it('describes every exported table and field as the schema has them', async () => {
		const expected = await format(reference(), { parser: 'markdown' });
		if (process.env.UPDATE_EXPORT_FORMAT) writeFileSync(REFERENCE, expected);
		// Out of date: run UPDATE_EXPORT_FORMAT=1 npx vitest run src/lib/server/export-format.spec.ts
		expect(readFileSync(REFERENCE, 'utf8')).toBe(expected);
	});
});
